"""Small DI-only instruction image for the CPU+bridge+SDRAM simulation (not a COM)."""
from pathlib import Path
r=Path(__file__).resolve().parent.parent
out=r/'sim/image33';out.mkdir(exist_ok=True)
rom=bytearray(256)
rom[:6]=bytes([0xf3,0x5b,0xc3,0x00,0x00,0x01])
rom[0x80:0x86]=bytes([0x3e,0xb7,0x32,0x00,0x90,0x76])
rom[0x90:0x96]=bytes([0x3e,0xd0,0x32,0x00,0x90,0x76])
code=bytearray();labels={};fix=[]
def emit(*b):code.extend(b)
def jp_fail():
 emit(0xc2);fix.append(len(code));emit(0,0,0)
def check(value):emit(0xfe,value);jp_fail()
# Native ADL data boundary, stack crossing, CALL/RET, aliases and unmapped accesses.
emit(0xf3,0x31,0x00,0x01,0x03,0x21,0xff,0xff,0x01)
emit(0x3e,0xa5,0x77,0x23,0x3e,0x5a,0x77,0x2b,0x7e);check(0xa5)
emit(0x23,0x7e);check(0x5a)
emit(0x31,0x01,0x00,0x02,0x21,0x56,0x34,0x12,0xe5,0xd1,0xeb)
emit(0x22,0x00,0x03,0x01,0x31,0x00,0x01,0x03)
emit(0xcd,0x00,0x02,0x01);check(0x5b)
# Short indirect accesses use MBASE and wrap within that bank; .SIL ignores
# the upper byte of its encoded address, while .LIS zero-extends 16-bit absolute.
emit(0x3e,0x01,0xed,0x6d,0x40,0x21,0xff,0xff,0x3e,0x22,0x40,0x77)
emit(0x52,0x3a,0xff,0xff,0x7f);check(0x22)
emit(0x40,0x23,0x3e,0x33,0x40,0x77,0x3a,0x00,0x00,0x01);check(0x33)
emit(0x49,0x3a,0x00,0x00);check(0xf3)
emit(0x3e,0x00,0xed,0x6d)
for bank,value in ((0x60,0x39),(0x61,0xe2),(0x62,0x77),(0x63,0x88),(0x40,0x95)):
 emit(0x21,0xff,0xff,bank,0x3e,value,0x77,0x7e);check(value)
emit(0x3a,0x00,0x00,0x64);check(0xff)
emit(0x21,0xff,0xff,0xff,0x3e,0x09,0x77)
emit(0x40,0xc3,0x80,0x00)
fail=len(code);emit(0x40,0xc3,0x90,0x00)
for i in fix:code[i:i+3]=(0x010000+fail).to_bytes(3,'little')
image=bytearray(1024);image[:len(code)]=code;image[0x200:0x202]=bytes([0x3c,0xc9])
for name,data in [('boot.hex',rom),('high.hex',image)]:
 (out/name).write_text(''.join(f'{b:02x}\n' for b in data))
(out/'program.txt').write_text('DI-only native ADL image at 010000; ROM entry JP.LIL 010000.\n'
 'Checks data/stack 01FFFF→020000, native CALL/RET, HL/DE 24-bit, all VRAM lanes, MegaRAM, unmapped, JP.SIS return.\n'
 'Simulation-only preload; this is not an MSX-DOS COM program.\n')
print('Generated CPU simulation image',len(code),'bytes')
